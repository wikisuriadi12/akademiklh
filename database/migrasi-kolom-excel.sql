ALTER TABLE santri
  ADD COLUMN nisn VARCHAR(20) NULL,
  ADD COLUMN nis_internal VARCHAR(20) NULL,
  ADD COLUMN nik VARCHAR(30) NULL,
  ADD COLUMN no_kk VARCHAR(20) NULL,
  ADD COLUMN va_lama VARCHAR(30) NULL,
  ADD COLUMN tgl_masuk DATE NULL,
  ADD COLUMN npsn_asal VARCHAR(20) NULL,
  ADD COLUMN alamat_asal VARCHAR(255) NULL,
  ADD COLUMN ayah_nama VARCHAR(120) NULL,
  ADD COLUMN ayah_nik VARCHAR(30) NULL,
  ADD COLUMN ayah_pendidikan VARCHAR(40) NULL,
  ADD COLUMN ayah_pekerjaan VARCHAR(80) NULL,
  ADD COLUMN ayah_penghasilan VARCHAR(60) NULL,
  ADD COLUMN ibu_nama VARCHAR(120) NULL,
  ADD COLUMN ibu_nik VARCHAR(30) NULL,
  ADD COLUMN ibu_pendidikan VARCHAR(40) NULL,
  ADD COLUMN ibu_pekerjaan VARCHAR(80) NULL,
  ADD COLUMN ibu_penghasilan VARCHAR(60) NULL,
  ADD COLUMN hp_ayah VARCHAR(30) NULL,
  ADD COLUMN hp_ibu VARCHAR(30) NULL,
  ADD COLUMN jumlah_saudara SMALLINT UNSIGNED NULL,
  ADD COLUMN anak_ke SMALLINT UNSIGNED NULL,
  ADD COLUMN tahun_ajaran VARCHAR(9) NULL,
  ADD COLUMN usia_masuk VARCHAR(20) NULL,
  ADD COLUMN keterangan VARCHAR(255) NULL,
  ADD KEY idx_santri_nisn (nisn),
  ADD KEY idx_santri_nik (nik);

DROP TABLE IF EXISTS santri_profil;

CREATE OR REPLACE VIEW data_santri_excel AS
SELECT
  kelas AS `KLS`,
  va_lama AS `VITUAL ACCOUNT`,
  nisn AS `NISN`,
  nis_internal AS `NIS`,
  nis AS `NIS LOKAL`,
  nik AS `NIK SISWA`,
  nama AS `NAMA SISWA`,
  tempat_lahir AS `TEMPAT LAHIR`,
  tanggal_lahir AS `TGL LAHIR`,
  usia_masuk AS `USIA MASUK`,
  CASE jenis_kelamin WHEN 'L' THEN 'LAKI-LAKI' ELSE 'PEREMPUAN' END AS `L/P`,
  tgl_masuk AS `TGL MASUK`,
  tahun_ajaran AS `TAHUN AJARAN`,
  alamat AS `ALAMAT`,
  npsn_asal AS `NPSN ASAL SEKOLAH`,
  asal_sekolah AS `NAMA ASAL SEKOLAH`,
  alamat_asal AS `ALAMAT ASAL SEKOLAH`,
  no_kk AS `KK`,
  ayah_nama AS `AYAH`,
  ayah_nik AS `NIK AYAH`,
  ayah_pendidikan AS `PENDIDIKAN AYAH`,
  ayah_pekerjaan AS `PEKERJAAN AYAH`,
  ayah_penghasilan AS `PENGHASILAN AYAH`,
  ibu_nama AS `IBU`,
  ibu_nik AS `NIK IBU`,
  ibu_pendidikan AS `PENDIDIKAN IBU`,
  ibu_pekerjaan AS `PEKERJAAN IBU`,
  ibu_penghasilan AS `PENGHASILAN IBU`,
  hp_ayah AS `NO. WA AYAH`,
  hp_ibu AS `NO. WA IBU`,
  jumlah_saudara AS `JUMLAH SAUDARA`,
  anak_ke AS `ANAK KE`,
  keterangan AS `KETERANGAN`,
  unit AS `UNIT`,
  status AS `STATUS`,
  id AS `ID`
FROM santri;
